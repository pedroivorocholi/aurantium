"""Regenerate the index member lists in ``aurantium/heatmap_universes.py``.

Scrapes the public Wikipedia constituents tables (S&P 500, Dow 30) and reads
the Nasdaq-100 from Nasdaq's own public list endpoint (Wikipedia's Nasdaq-100
page now lists company names with no tickers). Rewrites the block between the
``BEGIN MEMBERS`` / ``END MEMBERS`` markers, stamping ``MEMBERS_AS_OF``. Yahoo spells share classes with a dash
(BRK.B -> BRK-B), so symbols are normalised. Run on each release::

    .venv/Scripts/python.exe tools/data/refresh_index_members.py

Needs network, plus pandas and lxml (dev venv only; the app does not).
Refuses to write anything if a list looks wrong, so a changed page layout
cannot silently ship an empty or truncated universe.
"""

from __future__ import annotations

import io
import json
import re
import sys
import urllib.request
from datetime import date
from pathlib import Path

import pandas as pd

TARGET = Path(__file__).resolve().parents[2] / "aurantium" / "heatmap_universes.py"
UA = "aurantium-tools/1.0 (index member refresh)"

# name -> (page, accepted row-count range)
SOURCES = {
    "_SP500": ("List_of_S%26P_500_companies", (480, 520)),
    "_NDX": (None, (95, 110)),  # not on Wikipedia any more: see fetch_nasdaq100
    "_DOW": ("List_of_Dow_Jones_Industrial_Average_companies", (30, 30)),
}
_SYMBOL_COLS = ("symbol", "ticker")


def normalise(sym: str) -> str:
    return re.sub(r"[^A-Z0-9-]", "", str(sym).strip().upper().replace(".", "-"))


def fetch_members(page: str) -> tuple[str, ...]:
    req = urllib.request.Request(
        "https://en.wikipedia.org/wiki/" + page, headers={"User-Agent": UA}
    )
    html = urllib.request.urlopen(req, timeout=30).read().decode("utf-8")
    best: list[str] = []
    for table in pd.read_html(io.StringIO(html)):
        cols = {str(c).strip().lower(): c for c in table.columns}
        col = next((cols[c] for c in _SYMBOL_COLS if c in cols), None)
        if col is None:
            continue
        syms = [normalise(s) for s in table[col].dropna()]
        syms = [s for s in syms if s]
        if len(syms) > len(best):
            best = syms
    seen: dict[str, None] = {}
    for s in best:
        seen.setdefault(s)
    return tuple(seen)


def fetch_nasdaq100() -> tuple[str, ...]:
    req = urllib.request.Request(
        "https://api.nasdaq.com/api/quote/list-type/nasdaq100",
        headers={"User-Agent": "Mozilla/5.0", "Accept": "application/json"},
    )
    rows = json.load(urllib.request.urlopen(req, timeout=30))["data"]["data"]["rows"]
    return tuple(dict.fromkeys(normalise(r["symbol"]) for r in rows if r.get("symbol")))


def render(stamp: str, lists: dict[str, tuple[str, ...]]) -> str:
    out = [
        "# BEGIN MEMBERS (generated by tools/data/refresh_index_members.py)",
        f'MEMBERS_AS_OF = "{stamp}"',
    ]
    for name, members in lists.items():
        out.append(f"{name}: tuple[str, ...] = (")
        line = "   "
        for s in members:
            item = f' "{s}",'
            if len(line) + len(item) > 88:
                out.append(line)
                line = "   "
            line += item
        out.append(line)
        out.append(")")
    out.append("# END MEMBERS")
    return "\n".join(out)


def main() -> int:
    lists = {}
    for name, (page, (lo, hi)) in SOURCES.items():
        try:
            members = fetch_members(page) if page else fetch_nasdaq100()
        except Exception as exc:  # network / parse
            print(f"BLOCKED: could not fetch {page or name}: {exc}", file=sys.stderr)
            return 1
        if not lo <= len(members) <= hi:
            print(f"BLOCKED: {name} has {len(members)} members, expected {lo}-{hi}",
                  file=sys.stderr)
            return 1
        lists[name] = members
        print(f"{name}: {len(members)} members")
    text = TARGET.read_text(encoding="utf-8")
    block = render(date.today().isoformat(), lists)
    new, n = re.subn(r"# BEGIN MEMBERS.*?# END MEMBERS", lambda _m: block, text, flags=re.S)
    if n != 1:
        print("BLOCKED: member markers not found in heatmap_universes.py", file=sys.stderr)
        return 1
    TARGET.write_text(new, encoding="utf-8", newline="\n")
    print("wrote", TARGET)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
