_FIXED_LABELS = {
    "sectors": "Sectors",
    "portfolio": "Portfolio",
    "watchlist": "Watchlist",
    "custom": "Custom",
}


def view_label(view: str) -> str:
    """Human title for a heatmap view key (``sp500``, a sector value,
    ``portfolio``...). Unknown keys read as ``Custom``."""
    v = str(view or "").strip()
    if v.lower() in _FIXED_LABELS:
        return _FIXED_LABELS[v.lower()]
    if v.lower() in INDEXES:
        label, n, _ = INDEXES[v.lower()]
        return f"{label} · largest {n}"
    for key, label, _etf in SECTORS:
        if v.lower() == key.lower():
            return label
    return "Custom"
